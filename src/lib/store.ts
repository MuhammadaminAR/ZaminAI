export async function loadUser(userId: string): Promise<User | null> {
  const fetchAll = () => Promise.all([
    supabase.from("profiles").select("*").eq("id", userId).maybeSingle(),
    supabase.from("user_roles").select("role").eq("user_id", userId),
    supabase
      .from("subscriptions")
      .select("plan,status,created_at,expires_at")
      .eq("user_id", userId)
      .eq("status", "active")
      .order("created_at", { ascending: false })
      .limit(1),
  ]);
  let [{ data: profile }, { data: roles }, { data: subs }] = await fetchAll();
  if (!profile) {
    // Recovery: account setup didn't finish at signup. Idempotent, same DB function as the signup trigger.
    await supabase.rpc("ensure_my_profile");
    [{ data: profile }, { data: roles }, { data: subs }] = await fetchAll();
  }
  if (!profile) return null;
  const roleList = (roles ?? []).map((r) => r.role);
  const activeSub = (subs ?? []).find((s) => !s.expires_at || new Date(s.expires_at) > new Date());
  return {
    id: profile.id,
    email: profile.email,
    fullName: profile.full_name,
    role: roleList.includes("super_admin")
      ? "super_admin"
      : roleList.includes("admin")
        ? "admin"
        : roleList.includes("consultant")
          ? "consultant"
          : "farmer",
    plan: (activeSub?.plan as PlanId) ?? "free",
    createdAt: profile.created_at,
  };
}

export async function signUp(fullName: string, email: string, password: string) {
  const { data, error } = await supabase.auth.signUp({
    email,
    password,
    options: { emailRedirectTo: authCallbackUrl(), data: { full_name: fullName } },
  });
  if (error) {
    console.warn("[signup]", error.status, error.message);
    if (/database error/i.test(error.message)) {
      throw new Error("We couldn't create your account. Please try again.");
    }
    throw error;
  }
  // Existing email: Auth returns a user with no identities (no new account is created).
  if (data.user && (data.user.identities?.length ?? 0) === 0) {
    throw new Error("An account with this email already exists. Please log in or reset your password.");
  }
  if (data.session) {
    // Confirm-email is required; never treat an unexpected session as verified.
    if (!data.session.user.email_confirmed_at) await supabase.auth.signOut();
    else return { needsConfirmation: false };
  }
  return { needsConfirmation: true };
}

export class EmailNotConfirmedError extends Error {
  constructor() {
    super("Please verify your email address before signing in.");
  }
}

export async function signIn(email: string, password: string) {
  const { data, error } = await supabase.auth.signInWithPassword({ email, password });
  if (error) {
    if (error.code === "email_not_confirmed" || /not confirmed/i.test(error.message)) {
      throw new EmailNotConfirmedError();
    }
    if (error.code === "invalid_credentials") throw new Error("Incorrect email or password.");
    throw error;
  }
  if (!data.user?.email_confirmed_at) {
    await supabase.auth.signOut();
    throw new EmailNotConfirmedError();
  }
}

/** Resend the signup confirmation. Always resolves the same way to avoid revealing accounts. */
export async function resendConfirmation(email: string) {
  const { error } = await supabase.auth.resend({
    type: "signup",
    email,
    options: { emailRedirectTo: authCallbackUrl() },
  });
  if (error && (error.status === 429 || /rate limit|security purposes/i.test(error.message))) {
    throw new Error("Please wait a minute before requesting another email.");
  }
}

export async function signOut() {
  await supabase.auth.signOut();
}

export async function listUsers(): Promise<User[]> {
  const [{ data: profiles }, { data: roles }, { data: subs }] = await Promise.all([
    supabase.from("profiles").select("*").order("created_at", { ascending: false }),
    supabase.from("user_roles").select("user_id,role"),
    supabase.from("subscriptions").select("user_id,plan,status,created_at,expires_at").eq("status", "active"),
  ]);
  return (profiles ?? []).map((p) => {
    const r = (roles ?? []).filter((x) => x.user_id === p.id).map((x) => x.role);
    const sub = (subs ?? [])
      .filter((s) => s.user_id === p.id && (!s.expires_at || new Date(s.expires_at) > new Date()))
      .sort((a, b) => b.created_at.localeCompare(a.created_at))[0];
    return {
      id: p.id,
      email: p.email,
      fullName: p.full_name,
      role: r.includes("super_admin")
        ? ("super_admin" as const)
        : r.includes("admin")
          ? ("admin" as const)
          : r.includes("consultant")
            ? ("consultant" as const)
            : ("farmer" as const),
      plan: (sub?.plan as PlanId) ?? "free",
      createdAt: p.created_at,
    };
  });
}

/* ---------------- farms ---------------- */

type FarmRow = {
  id: string;
  user_id: string;
  name: string;
  location_name: string | null;
  latitude: number;
  longitude: number;
  area_hectares: number | null;
  created_at: string;
  country?: string | null;
  country_code?: string | null;
  region?: string | null;
  district?: string | null;
  locality?: string | null;
  formatted_address?: string | null;
  location_status?: string | null;
  salinity_risk_override?: string | null;
};

function toFarm(f: FarmRow): Farm {
  return {
    id: f.id,
    userId: f.user_id,
    name: f.name,
    areaHectares: Number(f.area_hectares ?? 0),
    location: {
      id: f.id,
      lat: f.latitude,
      lng: f.longitude,
      region:
        f.location_status === "resolved" ? (f.region ?? f.country ?? "Unknown region") : "Location needs review",
      country: f.country ?? null,
      countryCode: f.country_code ?? null,
      district: f.district ?? null,
      locality: f.locality ?? null,
      formattedAddress: f.formatted_address ?? null,
      locationStatus: f.location_status === "resolved" ? "resolved" : "needs_review",
      salinityRiskOverride: f.salinity_risk_override === "high" || f.salinity_risk_override === "standard" ? f.salinity_risk_override : null,
    },
    createdAt: f.created_at,
  };
}

export async function listFarms(userId: string): Promise<Farm[]> {
  const { data, error } = await supabase
    .from("farms")
    .select("*")
    .eq("user_id", userId)
    .order("created_at", { ascending: false });
  if (error) throw error;
  return (data ?? []).map(toFarm);
}

export async function deleteFarm(id: string) {
  const { error } = await supabase.from("farms").delete().eq("id", id);
  if (error) throw error;
}

