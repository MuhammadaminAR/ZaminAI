/** Saved 2016–2025 climate summary for an analysis (exact coordinates only). Only success/partial results are stored. */
export async function loadHistoricalClimate(analysisId: string): Promise<import("./historical-weather.server").HistoricalWeatherResult | null> {
  const { data, error } = await supabase
    .from("historical_climate_summaries")
    .select("payload, latitude, longitude")
    .eq("analysis_request_id", analysisId)
    .eq("start_date", "2016-01-01")
    .eq("end_date", "2025-12-31")
    .maybeSingle();
  if (error || !data) return null;
  return validatedSavedClimate(data.payload, data.latitude, data.longitude);
}

export async function saveHistoricalClimate(analysisId: string, r: import("./historical-weather.server").HistoricalWeatherResult) {
  // A failed dataset (e.g. HTTP 429) is not final: never freeze the gap; the server cache refetches only that dataset.
  if (!isSavableClimate(r)) return;
  const { error } = await supabase.from("historical_climate_summaries").insert({
    analysis_request_id: analysisId,
    latitude: r.requested.latitude,
    longitude: r.requested.longitude,
    start_date: r.start_date,
    end_date: r.end_date,
    status: r.status,
    payload: r as unknown as Json,
    fetched_at: r.fetched_at,
  });
  if (error) throw error;
}
